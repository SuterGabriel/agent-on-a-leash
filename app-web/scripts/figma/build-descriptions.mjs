#!/usr/bin/env node
/**
 * Builds the Figma component descriptions from design-system/component-map.json.
 * Prints a Plugin API script to stdout; Claude pastes it into the Figma MCP `use_figma` tool.
 * The script only replaces the part of each description after the ⟨code⟩ marker, so any text
 * a designer wrote above it is kept.
 *
 *   npm run figma:descriptions > /tmp/apply-descriptions.js
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const map = JSON.parse(fs.readFileSync(path.join(ROOT, "design-system/component-map.json"), "utf8"));

const out = {};
for (const c of [...map.components, ...(map.custom || [])]) {
    if (!c.figma?.nodeId) continue; // React-only (no Figma component yet)
    const from = c.react.import.match(/from "([^"]+)"/)?.[1] ?? "";
    const code = (t) => "`" + String(t).replace(/`/g, "'") + "`";
    const lines = [`**⟨code⟩ React** ${code(c.react.component)} from ${code(from)}`];
    const parts = [];
    for (const [k, v] of Object.entries(c.props || {})) {
        if (v.selectsComponent) continue;
        if (v.prop) {
            let s = `${k.split(" / ")[0]} → ${code(v.prop)}`;
            const vals = Object.entries(v.values || {})
                .filter(([a, b]) => b !== "omit" && a !== b)
                .map(([a, b]) => `${a}=${code(b)}`);
            if (vals.length) s += ` (${vals.join(", ")})`;
            parts.push(s);
        } else if (v.values) {
            const vals = Object.entries(v.values)
                .filter(([, b]) => b !== "omit")
                .map(([a, b]) => `${a}→${code(b)}`);
            if (vals.length) parts.push(`${k}: ${vals.join(", ")}`);
        }
    }
    if (parts.length) lines.push(`**Props** ${parts.join(" · ")}`);
    for (const [k, v] of Object.entries(c.props || {})) {
        if (v.selectsComponent)
            lines.push(
                `**${k} picks the component** ${Object.entries(v.selectsComponent)
                    .map(([a, b]) => `${a} → ${code(b.split(" from ")[0])}`)
                    .join("; ")}`,
            );
    }
    if (c.example) lines.push(`**Example** ${code(c.example)}`);
    lines.push("_Source: design-system/component-map.json_");
    out[c.figma.nodeId] = lines.join("\n\n");
}

process.stdout.write(`// Generated by scripts/figma/build-descriptions.mjs — run with the Figma MCP use_figma tool.
const MAP = ${JSON.stringify(out)};
const mutated = [], missing = [];
for (const [id, text] of Object.entries(MAP)) {
  const n = await figma.getNodeByIdAsync(id);
  if (!n || (n.type !== "COMPONENT_SET" && n.type !== "COMPONENT")) { missing.push(id); continue; }
  const keep = (n.descriptionMarkdown || n.description || "").split(/\\**⟨code⟩/)[0].trim();
  n.descriptionMarkdown = keep ? keep + "\\n\\n" + text : text;
  mutated.push(id + " " + n.name);
}
return { mutatedNodeIds: mutated, missing };
`);
